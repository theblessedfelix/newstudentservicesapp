type ScannerStudent = {
  id: string;
  studentId: string;
  name: string;
  initials: string;
};

type Level1StudentRecord = {
  id: number;
  studentId: string;
  name: string;
  campus: 'Lagos Island' | 'Lagos Mainland';
  level: 'Level 1';
};

function toInitials(name: string): string {
  return name
    .split(' ')
    .filter(Boolean)
    .map((part) => part[0]?.toUpperCase() ?? '')
    .join('')
    .slice(0, 3);
}

export function getLevel1ScannerStudents(): ScannerStudent[] {
  return Object.entries(level1StudentRegistry)
    .filter(([studentId]) => !LEVEL2_STUDENT_ID_SET.has(studentId))
    .map(([studentId, rawValue]) => {
    const [name] = rawValue.split(' - ');
    const cleanName = name.trim();

    return {
      id: studentId,
      studentId,
      name: cleanName,
      initials: toInitials(cleanName),
    };
  });
}

export function getLevel1StudentRecords(): Level1StudentRecord[] {
  return Object.entries(level1StudentRegistry)
    .filter(([studentId]) => !LEVEL2_STUDENT_ID_SET.has(studentId))
    .map(([studentId, rawValue]) => {
    const [rawName, rawCampus = 'Lagos Island'] = rawValue.split(' - ');
    const name = rawName.trim();
    const campus: 'Lagos Island' | 'Lagos Mainland' =
      rawCampus.toLowerCase().includes('island') ? 'Lagos Island' : 'Lagos Mainland';

    return {
      id: Number(studentId),
      studentId,
      name,
      campus,
      level: 'Level 1',
    };
  });
}
